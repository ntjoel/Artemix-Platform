function Merge-Messages {
    param(
        [string]$Path,
        [string]$LanguageKey,
        [hashtable]$Updates
    )

    $document = $null
    if (Test-Path $Path) {
        $document = [Newtonsoft.Json.Linq.JObject]::Parse((Get-Content -Path $Path -Raw))
    }

    $messages = [ordered]@{}
    if ($document -and $document["messages"]) {
        foreach ($property in $document["messages"].Properties()) {
            $messages[$property.Name] = $property.Value.ToString()
        }
    }

    foreach ($entry in $Updates.GetEnumerator()) {
        $messages[$entry.Key] = $entry.Value
    }

    $result = New-Object Newtonsoft.Json.Linq.JObject
    $result["key"] = New-Object Newtonsoft.Json.Linq.JValue($LanguageKey)
    $result["messages"] = New-Object Newtonsoft.Json.Linq.JObject

    foreach ($name in ($messages.Keys | Sort-Object)) {
        $result["messages"][$name] = New-Object Newtonsoft.Json.Linq.JValue($messages[$name])
    }

    $json = $result.ToString([Newtonsoft.Json.Formatting]::Indented)
    Set-Content -Path $Path -Value $json -Encoding UTF8
}

function Sync-MessageKeySet {
    param(
        [string]$SourcePath,
        [string]$TargetPath,
        [string]$TargetLanguageKey
    )

    if (-not (Test-Path $SourcePath)) {
        throw "Source message file not found: $SourcePath"
    }

    $sourceDocument = [Newtonsoft.Json.Linq.JObject]::Parse((Get-Content -Path $SourcePath -Raw))
    $targetDocument = $null
    if (Test-Path $TargetPath) {
        $targetDocument = [Newtonsoft.Json.Linq.JObject]::Parse((Get-Content -Path $TargetPath -Raw))
    }

    $sourceMessages = [ordered]@{}
    foreach ($property in $sourceDocument["messages"].Properties()) {
        $sourceMessages[$property.Name] = $property.Value.ToString()
    }

    $targetMessages = @{}
    if ($targetDocument -and $targetDocument["messages"]) {
        foreach ($property in $targetDocument["messages"].Properties()) {
            $targetMessages[$property.Name] = $property.Value.ToString()
        }
    }

    $alignedMessages = [ordered]@{}
    foreach ($name in ($sourceMessages.Keys | Sort-Object)) {
        if ($targetMessages.ContainsKey($name) -and -not [string]::IsNullOrWhiteSpace($targetMessages[$name])) {
            $alignedMessages[$name] = $targetMessages[$name]
        }
        else {
            $alignedMessages[$name] = $sourceMessages[$name]
        }
    }

    $result = New-Object Newtonsoft.Json.Linq.JObject
    $result["key"] = New-Object Newtonsoft.Json.Linq.JValue($TargetLanguageKey)
    $result["messages"] = New-Object Newtonsoft.Json.Linq.JObject

    foreach ($name in $alignedMessages.Keys) {
        $result["messages"][$name] = New-Object Newtonsoft.Json.Linq.JValue($alignedMessages[$name])
    }

    $json = $result.ToString([Newtonsoft.Json.Formatting]::Indented)
    Set-Content -Path $TargetPath -Value $json -Encoding UTF8
}

function Import-ToolLocalizationCatalog {
    param(
        [string]$Path,
        [System.Collections.IDictionary]$Target
    )

    if (-not (Test-Path $Path)) {
        return
    }

    $document = [Newtonsoft.Json.Linq.JObject]::Parse((Get-Content -Path $Path -Raw))
    if (-not $document["messages"]) {
        return
    }

    foreach ($property in $document["messages"].Properties()) {
        $Target[$property.Name] = $property.Value.ToString()
    }
}

